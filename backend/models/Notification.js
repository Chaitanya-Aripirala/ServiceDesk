const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    recipient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    type: {
      type: String,
      enum: ['TICKET_ASSIGNED', 'TICKET_UPDATED', 'SLA_WARNING', 'SLA_BREACH', 'ESCALATION', 'ASSET_ASSIGNED', 'SYSTEM_ALERT'],
      default: 'TICKET_UPDATED',
    },
    link: {
      type: String,
      default: '',
    },
    isRead: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Notification', notificationSchema);
